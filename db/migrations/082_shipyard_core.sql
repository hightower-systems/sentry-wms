-- 082: shipyard domain core.
--
-- This migration adds the first downstream domain layer without changing the
-- existing Sentry e-commerce order, item, or inventory semantics.
--
-- Core rules enforced at the database layer:
-- - a ship/project/drawing/manufacturer active binding is unique;
-- - one active primary storage bin is allowed per ship;
-- - an inbound manifest row is unique within its manifest;
-- - one inbound row creates exactly one cargo ticket;
-- - a pallet suffix is unique within its cargo ticket.
--
-- Inventory integration and cross-table "all pallets share the ticket bin"
-- checks are added in the service layer in later migrations.

SET lock_timeout = '5s';
SET statement_timeout = '120s';

BEGIN;

CREATE TABLE IF NOT EXISTS shipyard_project_bindings (
    binding_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ship_no                 VARCHAR(64) NOT NULL,
    engineering_no          VARCHAR(64) NOT NULL,
    production_drawing_no   VARCHAR(128) NOT NULL,
    manufacturer_name       VARCHAR(200) NOT NULL DEFAULT '',
    status                  VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    effective_from          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    effective_to            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT shipyard_project_binding_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT shipyard_project_binding_effective_window
        CHECK (effective_to IS NULL OR effective_to > effective_from)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_shipyard_project_binding_active
    ON shipyard_project_bindings
       (ship_no, engineering_no, production_drawing_no, manufacturer_name)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS ix_shipyard_project_binding_ship
    ON shipyard_project_bindings (ship_no, status);

CREATE TABLE IF NOT EXISTS shipyard_zone_ship_mappings (
    mapping_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bin_id          INT NOT NULL REFERENCES bins(bin_id),
    ship_no         VARCHAR(64) NOT NULL,
    is_primary      BOOLEAN NOT NULL DEFAULT TRUE,
    status          VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    effective_from  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    effective_to    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT shipyard_zone_ship_mapping_status
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT shipyard_zone_ship_mapping_effective_window
        CHECK (effective_to IS NULL OR effective_to > effective_from)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_shipyard_zone_ship_primary
    ON shipyard_zone_ship_mappings (ship_no)
    WHERE status = 'ACTIVE' AND is_primary;

CREATE UNIQUE INDEX IF NOT EXISTS uq_shipyard_zone_ship_bin
    ON shipyard_zone_ship_mappings (bin_id, ship_no)
    WHERE status = 'ACTIVE';

CREATE INDEX IF NOT EXISTS ix_shipyard_zone_ship_bin
    ON shipyard_zone_ship_mappings (bin_id, status);

CREATE TABLE IF NOT EXISTS shipyard_inbound_manifests (
    manifest_id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    warehouse_id            INT NOT NULL REFERENCES warehouses(warehouse_id),
    manifest_no             VARCHAR(128) NOT NULL,
    source_type             VARCHAR(16) NOT NULL DEFAULT 'EXCEL',
    source_file_name        VARCHAR(255),
    source_file_sha256      CHAR(64),
    source_template_version VARCHAR(32),
    original_file_url       TEXT,
    status                  VARCHAR(24) NOT NULL DEFAULT 'PARSED',
    metadata                JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by              VARCHAR(100) NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT shipyard_inbound_manifest_source_type
        CHECK (source_type IN ('EXCEL', 'CSV', 'PDF', 'IMAGE', 'MANUAL')),
    CONSTRAINT shipyard_inbound_manifest_status
        CHECK (status IN ('PARSED', 'CONFIRMED', 'PARTIAL', 'CLOSED', 'VOID')),
    CONSTRAINT shipyard_inbound_manifest_sha256
        CHECK (source_file_sha256 IS NULL OR length(source_file_sha256) = 64),
    CONSTRAINT uq_shipyard_inbound_manifest_no
        UNIQUE (warehouse_id, manifest_no)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_shipyard_inbound_manifest_file
    ON shipyard_inbound_manifests (warehouse_id, source_file_sha256)
    WHERE source_file_sha256 IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_shipyard_inbound_manifest_status
    ON shipyard_inbound_manifests (warehouse_id, status, created_at);

CREATE TABLE IF NOT EXISTS shipyard_inbound_lines (
    line_id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    manifest_id             UUID NOT NULL
                                REFERENCES shipyard_inbound_manifests(manifest_id)
                                ON DELETE CASCADE,
    source_row_no           VARCHAR(64) NOT NULL,
    source_row_hash         CHAR(64),
    ship_no                 VARCHAR(64) NOT NULL,
    engineering_no          VARCHAR(64) NOT NULL DEFAULT '',
    production_drawing_no   VARCHAR(128) NOT NULL DEFAULT '',
    drawing_name            TEXT,
    manufacturer_name       VARCHAR(200) NOT NULL DEFAULT '',
    delivery_note_no        VARCHAR(128),
    po_no                   VARCHAR(128),
    item_name               VARCHAR(255) NOT NULL,
    item_spec               TEXT,
    unit                    VARCHAR(32) NOT NULL DEFAULT '件',
    declared_quantity       NUMERIC(18,3) NOT NULL,
    assigned_bin_id         INT REFERENCES bins(bin_id),
    raw_data                JSONB NOT NULL DEFAULT '{}'::jsonb,
    status                  VARCHAR(24) NOT NULL DEFAULT 'PENDING',
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT shipyard_inbound_line_quantity
        CHECK (declared_quantity > 0),
    CONSTRAINT shipyard_inbound_line_hash
        CHECK (source_row_hash IS NULL OR length(source_row_hash) = 64),
    CONSTRAINT shipyard_inbound_line_status
        CHECK (status IN ('PENDING', 'RECEIVED', 'PARTIAL', 'EXCEPTION', 'VOID')),
    CONSTRAINT uq_shipyard_inbound_line_row
        UNIQUE (manifest_id, source_row_no)
);

ALTER TABLE shipyard_inbound_lines
    ADD COLUMN IF NOT EXISTS drawing_name TEXT,
    ADD COLUMN IF NOT EXISTS delivery_note_no VARCHAR(128),
    ADD COLUMN IF NOT EXISTS po_no VARCHAR(128);

CREATE INDEX IF NOT EXISTS ix_shipyard_inbound_line_ship
    ON shipyard_inbound_lines (ship_no, status);

CREATE INDEX IF NOT EXISTS ix_shipyard_inbound_line_bin
    ON shipyard_inbound_lines (assigned_bin_id, status);

CREATE TABLE IF NOT EXISTS shipyard_cargo_tickets (
    ticket_id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_no               VARCHAR(80) NOT NULL,
    inbound_line_id         UUID NOT NULL
                                REFERENCES shipyard_inbound_lines(line_id)
                                ON DELETE RESTRICT,
    item_id                 INT REFERENCES items(item_id),
    declared_quantity       NUMERIC(18,3) NOT NULL,
    received_quantity       NUMERIC(18,3) NOT NULL DEFAULT 0,
    expected_pallet_count   INT,
    assigned_bin_id         INT NOT NULL REFERENCES bins(bin_id),
    location_path_snapshot  VARCHAR(255) NOT NULL,
    stock_lot_number        VARCHAR(50) NOT NULL,
    status                  VARCHAR(24) NOT NULL DEFAULT 'EXPECTED',
    created_by              VARCHAR(100) NOT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_shipyard_cargo_ticket_no UNIQUE (ticket_no),
    CONSTRAINT uq_shipyard_cargo_ticket_line UNIQUE (inbound_line_id),
    CONSTRAINT uq_shipyard_cargo_ticket_lot UNIQUE (stock_lot_number),
    CONSTRAINT shipyard_cargo_ticket_declared_quantity
        CHECK (declared_quantity > 0),
    CONSTRAINT shipyard_cargo_ticket_received_quantity
        CHECK (received_quantity >= 0),
    CONSTRAINT shipyard_cargo_ticket_expected_pallets
        CHECK (expected_pallet_count IS NULL OR expected_pallet_count > 0),
    CONSTRAINT shipyard_cargo_ticket_status
        CHECK (status IN (
            'EXPECTED', 'PARTIAL', 'IN_STOCK', 'ALLOCATED', 'OUTBOUND',
            'CANCELLED', 'EXCEPTION'
        ))
);

CREATE INDEX IF NOT EXISTS ix_shipyard_cargo_ticket_status
    ON shipyard_cargo_tickets (status, assigned_bin_id);

CREATE INDEX IF NOT EXISTS ix_shipyard_cargo_ticket_item_lot
    ON shipyard_cargo_tickets (item_id, stock_lot_number);

CREATE TABLE IF NOT EXISTS shipyard_pallet_units (
    pallet_id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_id               UUID NOT NULL
                                REFERENCES shipyard_cargo_tickets(ticket_id)
                                ON DELETE CASCADE,
    tag_suffix              VARCHAR(32),
    qr_payload              TEXT NOT NULL,
    qr_payload_sha256       CHAR(64) NOT NULL,
    factory_pallet_no       VARCHAR(128),
    installation_pallet_no  VARCHAR(128),
    batch_no                VARCHAR(128),
    status                  VARCHAR(24) NOT NULL DEFAULT 'EXPECTED',
    received_by             VARCHAR(100),
    received_at             TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT shipyard_pallet_tag_suffix
        CHECK (tag_suffix IS NULL OR tag_suffix ~ '^[0-9]+-[0-9]+$'),
    CONSTRAINT shipyard_pallet_qr_sha256
        CHECK (length(qr_payload_sha256) = 64),
    CONSTRAINT shipyard_pallet_status
        CHECK (status IN (
            'EXPECTED', 'RECEIVED', 'STORED', 'OUTBOUND', 'EXCEPTION'
        )),
    CONSTRAINT uq_shipyard_pallet_ticket_suffix
        UNIQUE (ticket_id, tag_suffix)
);

CREATE INDEX IF NOT EXISTS ix_shipyard_pallet_ticket_status
    ON shipyard_pallet_units (ticket_id, status);

COMMIT;
